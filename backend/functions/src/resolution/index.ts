// ============================================
// Query Functions
// ============================================

export async function getScheduledResolutions(
  familyId: string
): Promise<Resolution[]> {
  const snapshot = await db()
    .collection('resolutions')
    .where('familyId', '==', familyId)
    .where('status', '==', 'scheduled')
    .orderBy('scheduledAt')
    .get();

  return snapshot.docs.map((doc) => doc.data() as Resolution);
}

export async function getResolutionsForRisk(riskId: string): Promise<Resolution[]> {
  const snapshot = await db()
    .collection('resolutions')
    .where('riskId', '==', riskId)
    .get();

  return snapshot.docs.map((doc) => doc.data() as Resolution);
}

// ============================================
// Helper Functions
// ============================================

async function getFamilyRules(familyId: string): Promise<FamilyRules | null> {
  const doc = await db().collection('familyRules').doc(familyId).get();
  if (!doc.exists) {
    return null;
  }
  return doc.data() as FamilyRules;
}

function generateResolutionId(riskId: string): string {
  const timestamp = Date.now();
  return `res_${riskId}_${timestamp}`;
}
